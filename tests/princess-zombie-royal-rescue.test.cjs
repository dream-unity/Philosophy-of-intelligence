const test = require('node:test');
const assert = require('node:assert/strict');

test('a stolen bottle restores Xero on contact, then takes the winner through both audiences across reloads', async () => {
  const folder = '../zelda-and-the-princess-zombie/';
  const {createWorld, tick, act, arrivalView} = await import(folder + 'world.mjs');
  const {storyFigure, storyPieces} = await import(folder + 'story-art.mjs');
  const {footHeight} = await import(folder + 'travel.mjs');
  const {restoreJourney} = await import(folder + 'journey-store.mjs');
  const {ROYAL_PHASE_SECONDS} = await import(folder + 'story.mjs');
  let w = createWorld();
  Object.assign(w, {greeted: true, route: 'unbound', hasMap: true, gateCrossed: true, reducedMotion: true});
  w.bag = {stock: {saveher: 1}, selected: 'saveher'};
  Object.assign(w.player, {x: 30.39, z: 1511.6, yaw: 0, pitch: 0, feetY: footHeight(w, 30.39, 1511.6)});
  tick(w, 0.1);
  assert.equal(w.milestones.reveal, true);
  assert.equal(w.dialogue, null, 'the discoverable encounter leaves the player free to aim');
  const figure = storyFigure(w);
  const distance = Math.hypot(figure.x - w.player.x, figure.z - w.player.z);
  w.player.yaw = Math.atan2(figure.x - w.player.x, figure.z - w.player.z);
  w.player.pitch = Math.atan2(figure.y + figure.h * 0.53 - (w.player.feetY + 1.43), distance) - 0.05;
  assert.ok(act(w, 'item:saveher'));
  assert.ok(!w.royalPrize, 'throwing alone does not rescue Xero');
  while (w.phialFlight) tick(w, 1 / 30);
  assert.equal(w.actors.find(a => a.type === 'princess').cured, true);
  assert.equal(w.royalPrize.phase, 'restoring');
  assert.equal(w.milestones.xeroSaved, true);
  assert.equal(w.ending, null);
  assert.equal(w.bag.stock.saveher, 0);
  assert.equal(storyFigure(w).restoration, 0);
  assert.ok(storyPieces(w).every(part => part.key !== 'silver-vial'), 'the thrown glass never appears a second time in Zelda’s hand');
  const feet = [w.player.x, w.player.z];
  const shot = arrivalView(w);
  assert.notEqual(shot.player, w.player);
  assert.deepEqual([w.player.x, w.player.z], feet);

  const advance = seconds => { for (let frame = 0; frame < Math.round(seconds * 30); frame++) tick(w, 1 / 30); };
  const reload = () => { w = restoreJourney(JSON.parse(JSON.stringify(w))); assert.ok(w); };
  advance(1);
  const partial = storyFigure(w).restoration;
  assert.ok(partial > 0 && partial < 1);
  reload();
  assert.equal(storyFigure(w).restoration, partial);
  advance(1.8);
  assert.equal(storyFigure(w).key, 'cured', 'the living face stays in view before the cut');
  advance(1);
  assert.equal(w.royalPrize.phase, 'report');
  assert.ok(w.actors.find(a => a.type === 'body').freed);
  reload();
  advance(ROYAL_PHASE_SECONDS.report);
  assert.equal(w.royalPrize.phase, 'honour');
  reload();
  advance(ROYAL_PHASE_SECONDS.honour);
  assert.equal(w.ending.id, 'saved');
  assert.equal(w.ending.prize, 'royal-honour');
  assert.equal(w.royalPrize.phase, 'complete');
  assert.equal(w.sequence, null);
  assert.equal(w.events.filter(e => e.type === 'ending').length, 1);
  assert.equal(w.journal.filter(e => e.id === 'royalHonour').length, 1);
  reload();
  advance(3);
  assert.equal(w.events.filter(e => e.type === 'ending').length, 0);
  assert.equal(w.ending.prize, 'royal-honour');
});
