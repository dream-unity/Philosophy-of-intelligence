import {renameSync, writeFileSync} from 'node:fs';
import {caseRoles, symbols, layoutFor, edgesFor, seededDraw, shuffled} from '../friend-or-foe/case-layout.js';
import {superEasyPatterns, evaluateSuperEasyPattern} from '../friend-or-foe/super-easy-patterns.js';

const target = Number(process.env.CASE_COUNT || 105);
const result = Object.fromEntries(superEasyPatterns.map(p => [p.id, []]));

// Certify boards where exact answer size is 2 AND flipping at least 3 individual
// rows yields a different valid answer (ensuring genuine multi-row sensitivity).
for (let seed = 1; ; seed++) {
  const rows = layoutFor(seed);
  if (!rows) continue;
  const base = edgesFor(rows, 0);
  const draw = seededDraw(seed * 919);

  for (const {id, order} of superEasyPatterns) {
    if (result[id].length >= target) continue;
    for (const anchor of (order.includes('{name}') ? shuffled(symbols, draw) : [symbols[0]])) {
      const pair = evaluateSuperEasyPattern(id, base, anchor, false).pair;
      if (pair.length !== 2) continue;
      let sensitiveRows = 0;
      for (let i = 0; i < caseRoles.length; i++) {
        const altPair = evaluateSuperEasyPattern(id, edgesFor(rows, 1 << i), anchor, false).pair;
        if (altPair.length !== 2 || altPair.some(n => !pair.includes(n))) sensitiveRows++;
      }
      if (sensitiveRows < 3) continue;
      result[id].push([seed, symbols.indexOf(anchor)]);
      break;
    }
  }

  if (Object.values(result).every(items => items.length >= target)) {
    const file = new URL('../friend-or-foe/super-easy-catalog.js', import.meta.url);
    const temporary = new URL(file + '.tmp-' + process.pid);
    writeFileSync(
      temporary,
      '// Generated by scripts/build-super-easy-catalog.mjs.\nexport const superEasyCatalog = ' + JSON.stringify(result) + ';\n'
    );
    renameSync(temporary, file);
    console.log('Done at seed', seed);
    break;
  }
}
