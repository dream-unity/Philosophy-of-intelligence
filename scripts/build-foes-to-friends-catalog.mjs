import {renameSync, writeFileSync} from 'node:fs';
import {caseRoles, symbols, layoutFor, edgesFor, seededDraw, shuffled} from '../foes-to-friends/case-layout.js';
import {patterns, evaluatePattern} from '../foes-to-friends/case-patterns.js';

const target = Number(process.env.CASE_COUNT || 105);
const firstSeed = Number(process.env.CASE_START || 1);
const result = Object.fromEntries(patterns.map(pattern => [pattern.id, []]));
const size = Array.from({length: 64}, (_, mask) => mask.toString(2).replaceAll('0', '').length);

// Certify spanning forests where every tree has size >= 2 (enabling irreducible
// coupled-cycle deductions with zero Verified handouts as well as mixed chains),
// and where flipping any branch leaves a *different* valid 2-name pair.
function certify(id, worlds, anchor, correct, draw) {
  const alternatives = worlds.map(edges => evaluatePattern(id, edges, anchor, false).pair);
  const eligible = alternatives.map((pair, mask) => pair.length === 2 &&
    pair.some(name => !correct.includes(name)) &&
    new Set(worlds[mask].flatMap(edge => [edge.from, edge.to])).size === symbols.length);

  const trees = Array(64);
  const forest = Array(64);
  forest[0] = [];
  for (let mask = 1; mask < 64; mask++) {
    if (eligible[mask]) {
      const roots = shuffled(caseRoles.map((_, i) => i), draw);
      for (const i of roots) {
        if (!(mask & (1 << i))) continue;
        const children = forest[mask ^ (1 << i)];
        if (!children) continue;
        trees[mask] = {role: i, children, mask};
        break;
      }
    }
    if (trees[mask]) forest[mask] = [trees[mask]];
    else {
      for (let part = (mask - 1) & mask; part > 0; part = (part - 1) & mask) {
        if (!trees[part] || !forest[mask ^ part]) continue;
        const option = [trees[part], ...forest[mask ^ part]];
        if (!forest[mask] || option.length < forest[mask].length) forest[mask] = option;
      }
    }
  }
  if (!forest[63] || forest[63].length > 2) return null;
  // Require at least one tree of size >= 2 in Hard so coupled non-tree deduction is always available.
  if (!forest[63].some(root => size[root.mask] >= 2)) return null;

  const moderate = shuffled(Array.from({length: 64}, (_, i) => i).filter(i => size[i] === 3 && trees[i]), draw)[0];
  if (moderate === undefined) return null;

  function encode(roots) {
    const parents = caseRoles.map(() => 7);
    function visit(node, parent) {
      parents[node.role] = parent;
      for (const child of node.children) visit(child, node.role);
    }
    for (const root of roots) visit(root, 6);
    return parents.reduce((n, parent, i) => n + parent * (8 ** i), 0);
  }
  return [encode([trees[moderate]]), encode(forest[63])];
}

function save() {
  const json = JSON.stringify(result);
  const file = new URL('../foes-to-friends/case-catalog.js', import.meta.url);
  const temporary = new URL(file + '.tmp-' + process.pid);
  writeFileSync(temporary,
    '// Generated by scripts/build-foes-to-friends-catalog.mjs.\nexport const caseCatalog = ' + json + ';\n');
  renameSync(temporary, file);
}

for (let seed = firstSeed; ; seed++) {
  const rows = layoutFor(seed);
  if (!rows) continue;
  const base = edgesFor(rows, 0);
  let worlds;
  const draw = seededDraw(seed * 713);
  for (const {id, order} of patterns) {
    if (result[id].length >= target) continue;
    for (const anchor of (order.includes('{name}') ? shuffled(symbols, draw) : [symbols[0]])) {
      const pair = evaluatePattern(id, base, anchor, false).pair;
      if (pair.length !== 2) continue;
      worlds ??= Array.from({length: 64}, (_, i) => edgesFor(rows, i));
      const flags = certify(id, worlds, anchor, pair, draw);
      if (!flags) continue;
      result[id].push([seed, symbols.indexOf(anchor), ...flags]);
      break;
    }
  }
  if (seed % 5000 === 0) {
    console.error(seed, Object.values(result).map(v => v.length).join(','));
  }
  if (Object.values(result).every(items => items.length >= target)) {
    save();
    console.log('Done at seed', seed);
    break;
  }
}
